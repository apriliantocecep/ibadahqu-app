export const DEFAULT_CITY = CITIES.find((c) => c.name === 'Jakarta')!;

/** Kota terdekat dari koordinat beserta jaraknya (km, perkiraan). */
export function nearestCity(lat: number, lng: number) {
  let best = CITIES[0];
  let bestD = Infinity;
  for (const c of CITIES) {
    const d = (c.lat - lat) ** 2 + ((c.lng - lng) * Math.cos((lat * Math.PI) / 180)) ** 2;
    if (d < bestD) {
      bestD = d;
      best = c;
    }
  }
  return { city: best, km: Math.sqrt(bestD) * 111.32 };
}
